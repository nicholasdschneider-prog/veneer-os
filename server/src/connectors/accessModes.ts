export function connectorAccessModeProfile(
  profiles: readonly ConnectorAccessModeProfile[] | undefined,
  mode: string | null | undefined,
  version?: number | null,
): ConnectorAccessModeProfile | null {
  if (!mode) return null;
  const matches = profiles?.filter((profile) => profile.mode === mode && (version == null || profile.version === version));
  return matches?.reduce<ConnectorAccessModeProfile | null>(
    (latest, profile) => !latest || profile.version > latest.version ? profile : latest,
    null,
  ) ?? null;
}

/** Only the newest immutable version for each mode is offered for a new
 * install. Exact older versions remain available for existing rows. */
export function latestConnectorAccessModeProfiles(
  profiles: readonly ConnectorAccessModeProfile[] | undefined,
): ConnectorAccessModeProfile[] {
  return CONNECTOR_ACCESS_MODES.flatMap((mode) => {
    const profile = connectorAccessModeProfile(profiles, mode);
    return profile ? [profile] : [];
  });
}
