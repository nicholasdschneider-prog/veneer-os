/**
 * Immutable connector access profiles. A change to scopes, tools, or promised
 * behavior needs a new version so existing installs keep their old snapshot.
 *
 * The model is provider-neutral. A custom connector can declare the same
 * modes later without a Composio policy (for example, for a read-only API key).
 */
export const CONNECTOR_ACCESS_MODES = ['read_only', 'full'] as const;
export type ConnectorAccessMode = (typeof CONNECTOR_ACCESS_MODES)[number];
export const COMPOSIO_OAUTH_SCOPE_STRATEGIES = ['explicit', 'managed_default'] as const;
export type ComposioOAuthScopeStrategy = (typeof COMPOSIO_OAUTH_SCOPE_STRATEGIES)[number];

export interface ComposioAccessPolicySnapshot {
  toolkitVersion: string;
  /** `managed_default` validates this immutable snapshot but does not send a
   * scope override. This is required when Composio's Google app rejects
   * narrower OAuth scopes. */
  oauthScopeStrategy: ComposioOAuthScopeStrategy;
  oauthScopes: readonly string[];
  toolSlugs: readonly string[];
}

export interface ConnectorAccessModeProfile {
  mode: ConnectorAccessMode;
  version: number;
  label: string;
  description: string;
  capabilities: readonly string[];
  /** Clear provider-level permission disclosure shown during install and in
   * access details. Agent tool limits can be narrower than the OAuth token. */
  providerPermissionNote?: string;
  recommended: boolean;
  composio?: ComposioAccessPolicySnapshot;
}

