/** Durable messages waiting behind the active turn, in execution order. */
export interface QueuedMessageSnapshot {
  id: number;
  text: string;
  createdAt: string;
  /** Present when another agent, the scheduler, or the build queue queued this message. Carries
   * internal provenance inside the runner; presentation boundaries strip it. */
  origin?: MessageOrigin;
  /** The live agent process already holds this text; the row is only a fallback. */
  delivered?: true;
}

/** An interrupted turn that exhausted automatic restart recovery. */
export interface FailedTurnSnapshot {
  prompt: string;
  attempts: number;
  error: string;
}

/** Server-authoritative non-transcript state sent on subscribe and every mutation. */
export interface ConversationQueueSnapshot {
  /** Monotonic creation order. A client must not apply an older snapshot. */
  revision: number;
  messages: QueuedMessageSnapshot[];
  failedTurn: FailedTurnSnapshot | null;
}

/** Friendly one-liners for the prototype's built-in tools. */
const TOOL_DISPLAY_NAMES: Record<string, string> = {
  WebSearch: 'Searching the web',
  WebFetch: 'Reading a web page',
  Read: 'Reading a file',
  Write: 'Writing a file',
  Edit: 'Editing a file',
  Task: 'Working on a subtask',
  TodoWrite: 'Organizing the plan',
};

export function displayNameForTool(toolName: string): string {
  const known = TOOL_DISPLAY_NAMES[toolName];
  if (known) return known;
  // The built-in ask_user tool renders its own interactive question card; give
  // its accompanying tool row a friendlier label than "Using agents".
  if (toolName === 'mcp__agents__ask_user') return 'Asking you a question';
  if (toolName === 'mcp__agents__request_secret') return 'Asking you for a secret';
  if (toolName === 'mcp__agents__reveal_secret') return 'Showing you a secret';
  if (toolName.startsWith('mcp__')) {
    const parts = toolName.split('__');
    return `Using ${parts[1] ?? 'a connection'}`;
  }
  return `Using ${toolName}`;
}

export function previewOf(value: unknown, max = 200): string {
  let text: string;
  if (typeof value === 'string') text = value;
  else {
    try {
      text = JSON.stringify(value) ?? '';
    } catch {
      text = String(value);
    }
  }
  text = text.replace(/\s+/g, ' ').trim();
  return text.length > max ? `${text.slice(0, max)}…` : text;
}
