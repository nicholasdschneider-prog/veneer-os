/**
 * Normalized event model (spec §6). All providers map into this; the UI
 * consumes only this. The full union is declared to keep the seam for
 * approvals/questions/documents, though the prototype only emits a subset.
 */

export type Channel = 'web' | 'email' | 'automation';
export type SubagentStatus = 'queued' | 'running' | 'completed' | 'stopped' | 'failed';
export type TurnOutcome = 'completed' | 'interrupted_by_user' | 'timed_out' | 'failed';

/** Authenticated origin for a prompt that was not authored by the human.
 * Omitted means the ordinary user authored the message. */
export interface MessageOrigin {
  kind: 'agent' | 'wakeup' | 'build_queue' | 'result_reply';
  /** Durable internal build activation; never inferred from prompt text. */
  buildDispatchId?: string;
  from: string;
  to: string;
  /** Viewer-safe marker for a message sent from another chat on this instance.
   * Unlike sourceConversationId, this does not grant or imply source access. */
  local?: true;
  /** Internal provenance used to resolve a viewer-authorized source link.
   * Presentation boundaries must strip this raw id before sending events. */
  sourceConversationId?: string;
  /** Send-time title paired with the internal source id. It follows the same
   * privacy rule and is stripped unless the viewer can access that source. */
  sourceConversationTitle?: string;
  /** Viewer-authorized source metadata. Never persist this presentation view. */
  sourceChat?: {
    id: string;
    title: string;
  };
}

export type AgentMessageDisposition = 'running' | 'steered' | 'delivered' | 'queued' | 'duplicate';

/** Structured sender-side receipt for mcp__agents__send_message. Raw target ids
 * stay server-side; presentation replaces them with viewer-authorized links. */
export interface AgentMessageToolDetails {
  kind: 'agent-message';
  text: string;
  targetConversationId?: string;
  remoteInstance?: string;
  disposition?: AgentMessageDisposition;
  messageId?: number;
  targetChat?: {
    id: string;
    title: string;
    agentName: string;
  };
}

/** Safe, provider-neutral aggregates for delegated work. Provider-native ids,
 * prompts, commands, logs, reasoning, results, and file paths never belong
 * here. Every field is optional because providers expose different detail. */
export interface SubagentProgress {
  startedAt?: string;
  durationMs?: number;
  currentAction?: string;
  actionCount?: number;
  filesChanged?: number;
  linesAdded?: number;
  linesRemoved?: number;
  resultLabel?: string;
}

export interface QuestionOption {
  label: string;
  value: string;
  description?: string;
}

/** Where a 'secret' prompt's value is written. The value itself never travels
 * through a prompt, an event, or the questions table. */
export interface QuestionSecretTarget {
  name: string;
  project: string | null;
  config: string | null;
  /** Best-effort: the name already has a value in that config. */
  exists?: boolean;
}

/** Public, provider-neutral question ids are generated by Veneer (q1, q2...). */
export interface QuestionPrompt {
  id: string;
  header?: string;
  question: string;
  options: QuestionOption[];
  multi: boolean;
  allowOther: boolean;
  /** Omitted means 'choice' (every pre-secret prompt). 'reveal' shows an
   * existing Doppler secret to the user only; the agent never sees the value. */
  kind?: 'choice' | 'secret' | 'reveal';
  secret?: QuestionSecretTarget;
}

export type QuestionAnswers = Record<string, string[]>;

