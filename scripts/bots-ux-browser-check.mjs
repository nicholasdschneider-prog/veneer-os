// Isolated fixture only. Argument: local Playwright module path.
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(process.argv[2]).href);
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const shot = name => page.screenshot({ path: `docs/reports/veneer-bots-ux/screenshots/${name}.png` });
const noOverflow = async () => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
try {
  await page.goto('http://127.0.0.1:3297/#/bots');
  const rail = page.getByRole('complementary', { name: 'Bot conversations' }).first();
  await rail.getByRole('button', { name: /Robin/ }).waitFor();
  assert.equal(await rail.getByRole('button', { name: /Atlas|Robin/ }).count(), 2);
  assert.equal(await page.getByLabel('Composing a reply').count(), 0);
  await noOverflow(); await shot('desktop-roster');
  await page.request.post('http://127.0.0.1:3297/fixture/presence');
  await rail.getByLabel('Composing a reply').waitFor();
  await shot('desktop-typing');
  await rail.getByLabel('Composing a reply').waitFor({ state: 'hidden' });
  await page.waitForTimeout(1400);
  assert.match(await rail.getByRole('button', { name: /Robin/ }).innerText(), /available/);
  await page.getByRole('button', { name: /Atlas.*Needs your input.*Which internal rollout/ }).click();
  await page.getByLabel('Message to bot').waitFor();
  assert.equal(await rail.isVisible(), true);
  await shot('desktop-decision');
  await rail.getByLabel('Find a bot').fill('robin');
  assert.equal(await rail.getByRole('button', { name: /Atlas/ }).count(), 0);
  await rail.getByLabel('Find a bot').fill('');
  await rail.getByRole('button', { name: /Robin/ }).click();
  await page.waitForTimeout(1200);
  assert.match(page.url(), /#\/chat\/robin\?from=bots/);
  if (errors.length) console.log(errors);
  await shot('desktop-chat');
  assert.equal(await rail.isVisible(), true);
  await noOverflow(); await shot('desktop-chat');
  await rail.getByRole('button', { name: 'VeneerBots', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByText('All bot conversations', { exact: true }).click();
  const mobileRail = page.getByRole('complementary', { name: 'Bot conversations' }).last();
  await mobileRail.getByRole('button', { name: /Robin/ }).waitFor();
  await noOverflow(); await shot('mobile-conversations');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.request.post('http://127.0.0.1:3297/fixture/presence');
  await mobileRail.getByLabel('Composing a reply').waitFor();
  assert.equal(await mobileRail.getByLabel('Composing a reply').locator('span').first().evaluate(el => getComputedStyle(el).animationName), 'none');
  await shot('mobile-typing');
  await page.context().setOffline(true);
  // Explicit socket closure emulates a disconnected transport without waiting for OS timeout.
  await page.evaluate(async () => { const { wsBus } = await import('/src/lib/ws.ts'); wsBus.socket.close(); });
  await mobileRail.getByLabel('Composing a reply').waitFor({ state: 'hidden' });
  await page.context().setOffline(false);
  await page.getByText('All bot conversations', { exact: true }).click();
  await page.getByRole('button', { name: /Atlas.*Needs your input.*Which internal rollout/ }).click();
  await page.getByLabel('Message to bot').waitFor();
  await shot('mobile-decision');
  await page.getByText('All bot conversations', { exact: true }).click();
  await mobileRail.getByRole('button', { name: /Robin/ }).click();
  await page.getByRole('button', { name: 'Back', exact: true }).waitFor();
  await noOverflow(); await shot('mobile-chat');
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await page.getByText('All bot conversations', { exact: true }).waitFor();
  await page.goto('http://127.0.0.1:3297/#/bots?register=1');
  await page.getByRole('heading', { name: /Register/ }).waitFor();
  await shot('mobile-registration');
  assert.deepEqual(errors, []);
  console.log('PASS: desktop/mobile rails, avatars, real runtime working → typing → available, reduced motion, disconnect, search, decision navigation, registration, no overflow or browser errors.');
} finally { await browser.close(); }
