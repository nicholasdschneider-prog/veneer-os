// Run only against the in-memory --teams fixture. No live customers or financial actions.
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(process.argv[2]).href);
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
const shot = name => page.screenshot({ path: `docs/reports/business-fleets/screenshots/${name}.png` });
try {
  await page.goto('http://127.0.0.1:3297/#/bots');
  const list = await (await page.request.get('http://127.0.0.1:3297/api/bots')).json();
  const ervp = list.teams.find(t => t.name === 'ERVP fixture').id;
  const other = list.teams.find(t => t.name === 'Other business fixture').id;
  const select = () => page.locator('select[aria-label="Business"]:visible').first();
  await select().selectOption(ervp);
  const rail = page.getByRole('complementary', { name: 'Bot conversations' }).first();
  await rail.getByRole('button', { name: /Atlas/ }).waitFor();
  await page.waitForTimeout(300);
  assert.equal(await rail.getByRole('button', { name: /Robin/ }).count(), 0);
  await shot('desktop-ervp');
  const staff = await (await page.request.get('http://127.0.0.1:3297/api/bots', { headers: { 'x-fixture-user': '2' } })).json();
  assert.equal(staff.bots.some(b => b.conversation_id === 'atlas'), false);
  const atlasDecision = list.decisions.find(d => d.conversation_id === 'atlas');
  assert.equal((await page.request.get(`http://127.0.0.1:3297/api/bots/decisions/${atlasDecision.id}`, { headers: { 'x-fixture-user': '2' } })).status(), 404);
  await page.getByText('ERVP fixture business access', { exact: true }).click();
  await page.getByLabel('Employee', { exact: true }).selectOption('2');
  await page.getByLabel('Business role', { exact: true }).selectOption('viewer');
  await page.getByRole('button', { name: 'Save access', exact: true }).click();
  await page.getByText('Jordan · viewer', { exact: true }).waitFor();
  const answer = await page.request.post(`http://127.0.0.1:3297/api/bots/decisions/${atlasDecision.id}/answer`, { headers: { 'x-fixture-user': '2' }, data: { expected_version: 1, request_key: 'unauthorized-fixture', action: 'approve', text: 'Internal fixture', scope: 'this_case' } });
  assert.equal(answer.status(), 403);
  await shot('desktop-business-access');
  await page.getByRole('button', { name: 'Remove access', exact: true }).click();
  await page.getByText('Jordan · viewer', { exact: true }).waitFor({ state: 'hidden' });
  await select().selectOption(other);
  await rail.getByRole('button', { name: /Robin/ }).waitFor();
  assert.equal(await rail.getByRole('button', { name: /Atlas/ }).count(), 0);
  await shot('desktop-other-business');
  await page.setViewportSize({ width: 390, height: 844 });
  await select().selectOption(ervp);
  await page.getByText('All bot conversations', { exact: true }).click();
  const mobileRail = page.getByRole('complementary', { name: 'Bot conversations' }).last();
  await mobileRail.getByRole('button', { name: /Atlas/ }).waitFor();
  assert.equal(await mobileRail.getByRole('button', { name: /Robin/ }).count(), 0);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await shot('mobile-business-roster');
  await page.getByText('All bot conversations', { exact: true }).click();
  await page.getByRole('button', { name: /Atlas.*Needs your input.*Which internal rollout/ }).click();
  await page.getByLabel('Message to bot').waitFor();
  await shot('mobile-business-decision');
  assert.deepEqual(errors, []);
  console.log('PASS: desktop/mobile business switching scopes roster and raised hands; owner grants/removes fixture viewer access; nonmember cannot read; viewer cannot answer another assigned human decision; native IDs retained; no overflow or browser exceptions.');
} finally { await browser.close(); }
