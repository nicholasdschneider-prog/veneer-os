import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(process.argv[2]).href);
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
const shot = name => page.screenshot({ path: `docs/reports/decision-history/screenshots/${name}.png` });
try {
  await page.goto('http://127.0.0.1:3297/#/bots');
  await page.locator('select[aria-label="Business"]:visible').first().selectOption('');
  const list = await (await page.request.get('http://127.0.0.1:3297/api/bots')).json();
  const archived = list.decisions.find(d => d.state === 'verified_completed');
  assert.equal((await page.request.get(`http://127.0.0.1:3297/api/bots/decisions/${archived.id}`, { headers: { 'x-fixture-user': '2' } })).status(), 404);
  const outsider = await (await page.request.get('http://127.0.0.1:3297/api/bots', { headers: { 'x-fixture-user': '2' } })).json();
  assert.equal(outsider.decisions.some(d => d.id === archived.id), false);
  const history = page.getByRole('region', { name: 'Completed / History' });
  const active = page.getByRole('region', { name: 'Following through' });
  const complete = history.getByRole('button', { name: /Fixture verified_completed-approve/ });
  await complete.waitFor();
  assert.equal(await complete.locator('[role="status"]').count(), 0);
  assert.equal(await active.getByRole('button').count(), 3);
  assert.equal(await history.getByRole('button').count(), 3);
  await active.getByText('Queued for execution', { exact: true }).waitFor();
  await active.getByText('Executing this task', { exact: true }).waitFor();
  await page.getByRole('region', { name: 'Needs attention' }).getByText('Failed', { exact: true }).waitFor();
  await page.getByRole('region', { name: 'Deferred', exact: true }).waitFor();
  await history.locator('h2').scrollIntoViewIfNeeded(); await shot('desktop-history');
  await page.request.post('http://127.0.0.1:3297/fixture/complete');
  await history.getByRole('button', { name: /Fixture running-approve/ }).waitFor({ timeout: 12000 });
  assert.equal(await active.getByRole('button').count(), 2);
  await complete.click();
  const detail = page.getByRole('region', { name: 'Decision thread' });
  await detail.getByText('Keep the wider shipment case open.', { exact: true }).waitFor();
  await detail.getByText('This internal scoped task only.', { exact: true }).waitFor();
  await detail.getByText('Internal email draft verified. Shipment remains pending.', { exact: true }).waitFor();
  assert.equal(await detail.getByRole('button', { name: 'approve', exact: true }).count(), 0);
  assert.equal(await detail.locator('[aria-label*="working" i]').count(), 0);
  await detail.getByText('Decision history', { exact: true }).click();
  assert.ok(await detail.locator('ol li').count() >= 4);
  await shot('desktop-history-detail');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await shot('mobile-history-detail');
  await page.goto('http://127.0.0.1:3297/#/bots');
  await history.locator('h2').scrollIntoViewIfNeeded(); await shot('mobile-history');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  console.log('PASS: scoped statuses, completed card without bot-wide activity, queued/running/blocked/failed/deferred/terminal disposition sections; transition automatically moves to history; discussion/answer/evidence retained; desktop/mobile navigation and no overflow. History list/detail ACL denies nonmember; audit retained. In-memory --history --teams fixture only.');
} finally { await browser.close(); }
